@app.get("/api/admin/analytics")
def admin_analytics():

    with db() as conn:

        users = conn.execute(
            """
            SELECT

                COUNT(*)
                FILTER (
                    WHERE role='student'
                )::int AS students,

                COUNT(*)
                FILTER (
                    WHERE role='faculty'
                )::int AS faculty,

                COUNT(*)
                FILTER (
                    WHERE role='admin'
                )::int AS admins,

                COUNT(*)::int AS total

            FROM users
            """
        ).fetchone()

        fee = conn.execute(
            """
            SELECT
                COALESCE(
                    SUM(semester_fee),
                    0
                ) AS total_fees,

                COALESCE(
                    SUM(paid),
                    0
                ) AS collected

            FROM fees
            """
        ).fetchone()

        attendance = conn.execute(
            """
            SELECT

                COUNT(*)::int AS total,

                COALESCE(
                    SUM(
                        CASE
                            WHEN present
                            THEN 1
                            ELSE 0
                        END
                    ),
                    0
                )::int AS present

            FROM attendance
            """
        ).fetchone()

    total = int(
        attendance["total"] or 0
    )

    present = int(
        attendance["present"] or 0
    )

    return {

        **dict(users),

        "total_fees":
            float(
                fee["total_fees"] or 0
            ),

        "collected":
            float(
                fee["collected"] or 0
            ),

        "attendance_percentage":
            round(
                present / total * 100,
                1
            )
            if total
            else 0,
    }