def rows(table):

    allowed = {
        "users",
        "attendance",
        "faculty_attendance",
        "assignments",
        "submissions",
        "notices",
        "results",
        "fees",
        "placements",
        "timetable",
    }

    if table not in allowed:
        raise ValueError("Invalid table")

    with db() as conn:

        return conn.execute(
            f"""
            SELECT *
            FROM {table}
            ORDER BY id
            """
        ).fetchall()


def clean(v):

    if isinstance(v, (datetime, date)):
        return v.isoformat()

    return v


def clean_rows(items):

    cleaned = []

    for item in items:

        row = {}

        for key, value in dict(item).items():

            # Never send the actual binary file
            # through /api/state.
            if key == "file_data":
                continue

            row[key] = clean(value)

        cleaned.append(row)

    return cleaned


