@app.get("/api/state")
def state():

    with db() as conn:

        users = conn.execute(
            """
            SELECT *
            FROM users
            ORDER BY id
            """
        ).fetchall()

        attendance = conn.execute(
            """
            SELECT
                id,
                student_id,
                subject,
                date,
                present
            FROM attendance
            ORDER BY id
            """
        ).fetchall()

        faculty_attendance = conn.execute(
            """
            SELECT
                id,
                faculty_id,
                date,
                present
            FROM faculty_attendance
            ORDER BY id
            """
        ).fetchall()

        assignments = conn.execute(
            """
            SELECT
                a.*,
                u.name AS creator_name
            FROM assignments a
            LEFT JOIN users u
              ON u.id = a.created_by
            ORDER BY a.id DESC
            """
        ).fetchall()

        submissions = conn.execute(
            """
            SELECT
                s.id,
                s.assignment_id,
                s.student_id,
                s.submitted_at,
                s.file_name,
                s.status,
                s.marks,
                s.feedback,
                s.mime_type,
                s.file_size,
                s.student_notes,

                u.name AS student_name,
                u.roll_no,
                u.email AS student_email,

                a.title AS assignment_title,
                a.subject,
                a.created_by AS assignment_faculty_id

            FROM submissions s

            LEFT JOIN users u
              ON u.id = s.student_id

            LEFT JOIN assignments a
              ON a.id = s.assignment_id

            ORDER BY s.id DESC
            """
        ).fetchall()

        notices = conn.execute(
            """
            SELECT *
            FROM notices
            ORDER BY id DESC
            """
        ).fetchall()

        results = conn.execute(
            """
            SELECT
                r.*,
                u.name AS student_name,
                u.roll_no
            FROM results r
            LEFT JOIN users u
              ON u.id = r.student_id
            ORDER BY r.id DESC
            """
        ).fetchall()

        fees = conn.execute(
            """
            SELECT
                f.*,
                u.name AS student_name,
                u.email,
                u.roll_no,
                u.department
            FROM fees f
            LEFT JOIN users u
              ON u.id = f.student_id
            ORDER BY f.id
            """
        ).fetchall()

        placements = conn.execute(
            """
            SELECT *
            FROM placements
            ORDER BY id
            """
        ).fetchall()

        timetable = conn.execute(
            """
            SELECT *
            FROM timetable
            ORDER BY id
            """
        ).fetchall()

    return {

        "users":
            clean_rows(users),

        "attendance":
            clean_rows(attendance),

        "faculty_attendance":
            clean_rows(faculty_attendance),

        "assignments":
            clean_rows(assignments),

        "submissions":
            clean_rows(submissions),

        "notices":
            clean_rows(notices),

        "results":
            clean_rows(results),

        "fees":
            clean_rows(fees),

        "placements":
            clean_rows(placements),

        "timetable":
            clean_rows(timetable),
    }


