@app.get(
    "/api/submissions/{submission_id}/file"
)
def download_submission(
    submission_id: int
):

    with db() as conn:

        row = conn.execute(
            """
            SELECT
                file_data,
                file_name,
                mime_type
            FROM submissions
            WHERE id=%s
            """,
            (submission_id,)
        ).fetchone()

    if not row:

        raise HTTPException(
            status_code=404,
            detail="Submission not found"
        )

    if not row["file_data"]:

        raise HTTPException(
            status_code=404,
            detail="No uploaded file exists."
        )

    filename = (
        row["file_name"]
        or "submission"
    )

    mime = (
        row["mime_type"]
        or "application/octet-stream"
    )

    return Response(
        content=bytes(row["file_data"]),
        media_type=mime,
        headers={
            "Content-Disposition":
                f'attachment; filename="{filename}"'
        }
    )


