def prepare_database():
    """
    Makes existing BIGINT id columns auto-generate IDs.

    This fixes:
    - Add Student
    - Add Faculty
    - Create Assignment
    - Add Result
    - Add Notice
    - Attendance
    - Faculty Attendance
    - Assignment Submission

    Also adds columns required for real uploaded files.
    """

    with db() as conn:

        # ----------------------------------------------------
        # Make existing ID columns identity columns
        # ----------------------------------------------------

        for table in TABLES:

            try:
                identity = conn.execute(
                    """
                    SELECT a.attidentity
                    FROM pg_attribute a
                    JOIN pg_class c
                      ON c.oid = a.attrelid
                    WHERE c.relname = %s
                      AND a.attname = 'id'
                      AND a.attnum > 0
                      AND NOT a.attisdropped
                    """,
                    (table,)
                ).fetchone()

                if identity and identity["attidentity"] == "":
                    conn.execute(
                        f"""
                        ALTER TABLE {table}
                        ALTER COLUMN id
                        ADD GENERATED BY DEFAULT AS IDENTITY
                        """
                    )

            except Exception as exc:
                print(
                    f"Identity setup warning for {table}: {exc}"
                )

        # ----------------------------------------------------
        # Submission file storage
        # ----------------------------------------------------

        conn.execute(
            """
            ALTER TABLE submissions
            ADD COLUMN IF NOT EXISTS file_data BYTEA
            """
        )

        conn.execute(
            """
            ALTER TABLE submissions
            ADD COLUMN IF NOT EXISTS mime_type TEXT
            """
        )

        conn.execute(
            """
            ALTER TABLE submissions
            ADD COLUMN IF NOT EXISTS file_size BIGINT
            """
        )

        conn.execute(
            """
            ALTER TABLE submissions
            ADD COLUMN IF NOT EXISTS student_notes TEXT
            """
        )

        # ----------------------------------------------------
        # Synchronize identity sequences with existing IDs
        # ----------------------------------------------------

        for table in TABLES:

            try:

                sequence = conn.execute(
                    """
                    SELECT pg_get_serial_sequence(
                        %s,
                        'id'
                    ) AS sequence
                    """,
                    (table,)
                ).fetchone()

                if sequence and sequence["sequence"]:

                    maximum = conn.execute(
                        f"""
                        SELECT COALESCE(MAX(id), 0) AS maximum
                        FROM {table}
                        """
                    ).fetchone()["maximum"]

                    if maximum and int(maximum) > 0:

                        conn.execute(
                            """
                            SELECT setval(
                                %s::regclass,
                                %s,
                                true
                            )
                            """,
                            (
                                sequence["sequence"],
                                int(maximum),
                            )
                        )

            except Exception as exc:
                print(
                    f"Sequence setup warning for {table}: {exc}"
                )

        conn.commit()


@app.on_event("startup")
def startup():
    print("Preparing PostgreSQL database...")
    prepare_database()
    print("PostgreSQL database ready.")


