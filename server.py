@app.post(
    "/api/assignments/{assignment_id}/submit"
)
async def upload_assignment(
    assignment_id: int,
    student_id: int = Form(...),
    student_notes: str = Form(""),
    file: UploadFile = File(...)
):

    # --------------------------------------------------------
    # Maximum upload size: 5 MB
    # --------------------------------------------------------

    MAX_SIZE = 5 * 1024 * 1024

    file_data = await file.read()

    if not file_data:

        raise HTTPException(
            status_code=400,
            detail="The uploaded file is empty."
        )

    if len(file_data) > MAX_SIZE:

        raise HTTPException(
            status_code=413,
            detail="File is too large. Maximum size is 5 MB."
        )

    # --------------------------------------------------------
    # Verify file type
    # --------------------------------------------------------

    allowed_extensions = {
        ".pdf",
        ".doc",
        ".docx",
        ".zip",
        ".txt",
        ".ppt",
        ".pptx",
        ".xls",
        ".xlsx",
        ".csv",
        ".jpg",
        ".jpeg",
        ".png",
        ".webp",
    }

    filename = (
        file.filename
        or "submission"
    )

    filename = (
        filename
        .replace('"', "")
        .replace("\r", "")
        .replace("\n", "")
)

    extension = os.path.splitext(
        filename
    )[1].lower()

    if extension not in allowed_extensions:

        raise HTTPException(
            status_code=400,
            detail=(
                "Unsupported file type. "
                "Allowed: PDF, DOC, DOCX, ZIP, "
                "PPT, PPTX, XLS, XLSX, CSV, "
                "TXT and common images."
            )
        )

    # --------------------------------------------------------
    # Verify assignment + student
    # --------------------------------------------------------

    with db() as conn:

        assignment = conn.execute(
            """
            SELECT *
            FROM assignments
            WHERE id=%s
            """,
            (assignment_id,)
        ).fetchone()

        if not assignment:

            raise HTTPException(
                status_code=404,
                detail="Assignment not found"
            )

        student = conn.execute(
            """
            SELECT *
            FROM users
            WHERE id=%s
              AND role='student'
            """,
            (student_id,)
        ).fetchone()

        if not student:

            raise HTTPException(
                status_code=404,
                detail="Student not found"
            )

        # ----------------------------------------------------
        # Prevent accidental duplicate submission
        # ----------------------------------------------------

        existing = conn.execute(
            """
            SELECT id
            FROM submissions
            WHERE assignment_id=%s
              AND student_id=%s
            ORDER BY id DESC
            LIMIT 1
            """,
            (
                assignment_id,
                student_id
            )
        ).fetchone()

        submitted = datetime.now().isoformat(
            timespec="seconds"
        )

        if existing:

            row = conn.execute(
                """
                UPDATE submissions

                SET
                    submitted_at=%s,
                    file_name=%s,
                    status='Submitted',
                    marks=NULL,
                    feedback=NULL,
                    file_data=%s,
                    mime_type=%s,
                    file_size=%s,
                    student_notes=%s

                WHERE id=%s

                RETURNING *
                """,
                (
                    submitted,
                    filename,
                    file_data,
                    file.content_type
                    or "application/octet-stream",
                    len(file_data),
                    student_notes,
                    existing["id"]
                )
            ).fetchone()

        else:

            row = conn.execute(
                """
                INSERT INTO submissions
                (
                    assignment_id,
                    student_id,
                    submitted_at,
                    file_name,
                    status,
                    marks,
                    feedback,
                    file_data,
                    mime_type,
                    file_size,
                    student_notes
                )

                VALUES
                (
                    %s,
                    %s,
                    %s,
                    %s,
                    'Submitted',
                    NULL,
                    NULL,
                    %s,
                    %s,
                    %s,
                    %s
                )

                RETURNING *
                """,
                (
                    assignment_id,
                    student_id,
                    submitted,
                    filename,
                    file_data,
                    file.content_type
                    or "application/octet-stream",
                    len(file_data),
                    student_notes
                )
            ).fetchone()

    return clean_rows([row])[0]


