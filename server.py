@app.get("/api/attendance/{student_id}")
def student_attendance(student_id: int):

    with db() as conn:

        data = conn.execute(
            """
            SELECT
                subject,
                COUNT(*)::int AS total,
                SUM(
                    CASE
                        WHEN present
                        THEN 1
                        ELSE 0
                    END
                )::int AS present

            FROM attendance

            WHERE student_id=%s

            GROUP BY subject

            ORDER BY subject
            """,
            (student_id,)
        ).fetchall()

    result = []

    for r in data:

        total = int(
            r["total"] or 0
        )

        present = int(
            r["present"] or 0
        )

        result.append({

            "subject":
                r["subject"],

            "total":
                total,

            "present":
                present,

            "percentage":
                round(
                    (present / total) * 100,
                    1
                )
                if total
                else 0,
        })

    return result


