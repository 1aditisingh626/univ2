@app.get("/api/fees")
def get_fees():

    with db() as conn:

        data = conn.execute(
            """
            SELECT
                f.*,
                u.name AS student_name,
                u.email,
                u.roll_no,
                u.department

            FROM fees f

            LEFT JOIN users u
              ON u.id=f.student_id

            ORDER BY f.id
            """
        ).fetchall()

    return clean_rows(data)


@app.get("/api/fees/{student_id}")
def get_student_fee(
    student_id: int
):

    with db() as conn:

        row = conn.execute(
            """
            SELECT
                f.*,
                u.name AS student_name,
                u.email,
                u.roll_no,
                u.department

            FROM fees f

            LEFT JOIN users u
              ON u.id=f.student_id

            WHERE f.student_id=%s

            LIMIT 1
            """,
            (student_id,)
        ).fetchone()

    if not row:

        raise HTTPException(
            status_code=404,
            detail="Fee record not found"
        )

    return clean_rows([row])[0]


@app.post("/api/fees/pay")
def pay_fee(
    payload: FeeRequest
):

    if payload.amount <= 0:

        raise HTTPException(
            status_code=400,
            detail="Amount must be positive"
        )

    with db() as conn:

        row = conn.execute(
            """
            UPDATE fees

            SET paid =
                LEAST(
                    semester_fee,
                    paid + %s
                )

            WHERE student_id=%s

            RETURNING *
            """,
            (
                payload.amount,
                payload.student_id
            )
        ).fetchone()

    if not row:

        raise HTTPException(
            status_code=404,
            detail="Fee record not found"
        )

    return clean_rows([row])[0]


